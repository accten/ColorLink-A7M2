/**
 * 生成两个测试用 .cube LUT：
 *  - sample-identity.cube   恒等表：用来验证"导入成功但画面不该变"
 *  - sample-teal-orange.cube 青橙：暗部偏青、亮部偏暖 + 轻 S 曲线，肉眼可辨
 *
 * 运行：node scripts/gen-sample-luts.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(ROOT, 'luts');
const SIZE = 17;

const clamp01 = (v) => (v < 0 ? 0 : v > 1 ? 1 : v);
const smooth = (e0, e1, x) => {
  const t = clamp01((x - e0) / (e1 - e0));
  return t * t * (3 - 2 * t);
};
const fmt = (v) => clamp01(v).toFixed(4);

function writeCube(name, title, transform) {
  const lines = [
    `# ${title}`,
    `# Generated by scripts/gen-sample-luts.mjs for ColorLink LUT import test`,
    `TITLE "${title}"`,
    `LUT_3D_SIZE ${SIZE}`,
    'DOMAIN_MIN 0 0 0',
    'DOMAIN_MAX 1 1 1',
    '',
  ];

  for (let b = 0; b < SIZE; b++) {
    for (let g = 0; g < SIZE; g++) {
      for (let r = 0; r < SIZE; r++) {
        const inR = r / (SIZE - 1);
        const inG = g / (SIZE - 1);
        const inB = b / (SIZE - 1);
        const [outR, outG, outB] = transform(inR, inG, inB);
        lines.push(`${fmt(outR)} ${fmt(outG)} ${fmt(outB)}`);
      }
    }
  }

  const file = join(OUT, name);
  writeFileSync(file, lines.join('\n') + '\n');
  console.log('generated', file);
}

mkdirSync(OUT, { recursive: true });

writeCube('sample-identity.cube', 'Identity 17', (r, g, b) => [r, g, b]);

writeCube('sample-teal-orange.cube', 'Teal Orange 17', (r, g, b) => {
  const lum = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  const warm = smooth(0.45, 1.0, lum);
  const cool = 1 - smooth(0.0, 0.55, lum);

  let outR = r + 0.10 * warm - 0.02 * cool;
  let outG = g + 0.02 * warm + 0.01 * cool;
  let outB = b - 0.06 * warm + 0.09 * cool;

  // 轻 S 曲线：中灰不动，两端更硬
  const curve = (v) => (v - 0.5) * 1.08 + 0.5;
  return [clamp01(curve(outR)), clamp01(curve(outG)), clamp01(curve(outB))];
});
